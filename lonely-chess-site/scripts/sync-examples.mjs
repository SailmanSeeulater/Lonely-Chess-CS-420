// Regenerates lib/examples.ts from the repository's .pgn files so the site
// can never show a stale copy of a sample program. Runs before every build.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "..", "..");
const outFile = path.resolve(here, "..", "lib", "examples.ts");

const FILES = [
  "sample_int100.pgn",
  "sample_int95.pgn",
  "sample_str_hello.pgn",
  "sample_arithmetic.pgn",
  "sample_dom_dabish.pgn",
  "fizzbuzz_complete.pgn",
  "fizzbuzz_100.pgn",
  "actual_game_sample.pgn",
];

const missing = FILES.filter((name) => !fs.existsSync(path.join(repoRoot, name)));
if (missing.length) {
  // Builds that copy only lonely-chess-site/ (e.g. the VPS Docker image) can't see the repo root;
  // the committed lib/examples.ts is then the source, regenerated on any full checkout.
  if (fs.existsSync(outFile)) {
    console.log("sync-examples: repo .pgn files not found; keeping the committed lib/examples.ts");
    process.exit(0);
  }
  console.error(`sync-examples: missing in ${repoRoot}: ${missing.join(", ")}`);
  process.exit(1);
}

const entries = FILES.map((name) => {
  const text = fs.readFileSync(path.join(repoRoot, name), "utf8").replace(/\r\n/g, "\n");
  return `  ${JSON.stringify(name)}: ${JSON.stringify(text)},`;
});

const source = `// Generated by scripts/sync-examples.mjs from the repository's .pgn files.
// Do not edit by hand — edit the .pgn file and run \`npm run sync-examples\`.

export const PGN_EXAMPLES = {
${entries.join("\n")}
} as const;

export type ExampleName = keyof typeof PGN_EXAMPLES;
`;

fs.writeFileSync(outFile, source);
console.log(`sync-examples: wrote ${FILES.length} programs to lib/examples.ts`);
